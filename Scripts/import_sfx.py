"""
Grapple Runner: import the game's own sound effects (made in Tools/) into Unreal.

Run:  py "C:/Users/User/Documents/Unreal Projects/GrappleRunner/Scripts/import_sfx.py"

- Imports every .wav in <Project>/Art/SFX/ into /Game/GrappleRunner/SFX.
- Sounds whose names start with SFX_Wind are set to loop (the wind plays all the time;
  GrappleRig turns its volume up and down with your speed).
- These sounds are generated by our own scripts, so they can go in the public repo.

HOW TO READ THIS (no coding experience needed)
- Lines starting with # are notes for humans; the computer skips them.
- "import unreal" loads Unreal Engine's own Python toolbox.
"""
import os
import unreal

PROJECT = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())
SRC = os.path.join(PROJECT, "Art", "SFX")
DEST = "/Game/GrappleRunner/SFX"

tasks = []
for name in sorted(os.listdir(SRC)) if os.path.isdir(SRC) else []:
    if name.lower().endswith(".wav"):
        t = unreal.AssetImportTask()
        t.set_editor_property("filename", os.path.join(SRC, name))
        t.set_editor_property("destination_path", DEST)
        t.set_editor_property("automated", True)
        t.set_editor_property("replace_existing", True)
        t.set_editor_property("save", True)
        tasks.append(t)
unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)

for t in tasks:
    for path in t.get_editor_property("imported_object_paths"):
        asset = unreal.load_asset(path)
        if asset and asset.get_name().startswith("SFX_Wind"):
            asset.set_editor_property("looping", True)        # play forever
            unreal.EditorAssetLibrary.save_asset(path.split(".")[0])
unreal.log("Grapple Runner SFX: imported {} sounds".format(len(tasks)))
